-- 1. Имена врачей и их направления (INNER JOIN)
SELECT "Врачи"."Имя", "Направление"."Название"
FROM "Направление врача"
INNER JOIN "Врачи" ON "Направление врача"."Врач" = "Врачи"."Врач_id"
INNER JOIN "Направление" ON "Направление врача"."Направление" = "Направление"."направление_id";

-- 2. Список больниц
SELECT "Больница_id", "Название"
FROM "Больница";

-- 3. Расчёт примерного возраста начала карьеры врачей
SELECT "Врач_id", "Имя", "Фамилия", "Отчество", ("Возраст" - "Стаж") AS "Возраст_начала_карьеры"
FROM "Врачи";

-- 4. Уникальные учебные заведения врачей
SELECT DISTINCT "Образование"
FROM "Врачи";

-- 5. Общее количество графиков работы
SELECT COUNT(*)
FROM "Расписание работы";

-- 6. Количество уникальных смен в понедельник
SELECT COUNT(DISTINCT "Понедельник")
FROM "Расписание работы";

-- 7. Графики с утренней сменой в понедельник
SELECT *
FROM "Расписание работы"
WHERE "Понедельник" = '08:00-14:00';

-- 8. Графики, где во вторник смена отличается от утренней
SELECT *
FROM "Расписание работы"
WHERE "Вторник" != '08:00-14:00';

-- 9. Записи на приём с ID процедуры >= 6
SELECT *
FROM "Расписание приёма"
WHERE "Процедура" >= 6;

-- 10. Графики с выходными в среду и субботу
SELECT *
FROM "Расписание работы"
WHERE "Среда" = 'Выходной' AND "Суббота" = 'Выходной';

-- 11. Графики с выходным во вторник или среду
SELECT *
FROM "Расписание работы"
WHERE "Вторник" = 'Выходной' OR "Среда" = 'Выходной';

-- 12. Комбинированное условие по выходным дням
SELECT *
FROM "Расписание работы"
WHERE "Вторник" = 'Выходной' OR ("Среда" = 'Выходной' AND "Суббота" = 'Выходной');

-- 13. Приёмы у врачей с ID от 3 до 7
SELECT *
FROM "Расписание приёма"
WHERE "Врач" BETWEEN 3 AND 7;

-- 14. Сложное условие с BETWEEN, AND и OR
SELECT *
FROM "Расписание приёма"
WHERE ("Врач" BETWEEN 3 AND 7 AND "Процедура" = 8) OR "Пациент" = 10;

-- 15. Приёмы для указанного списка пациентов (IN)
SELECT *
FROM "Расписание приёма"
WHERE "Пациент" IN (3, 4, 5, 6);

-- 16. Приёмы, исключая указанных пациентов (NOT IN)
SELECT *
FROM "Расписание приёма"
WHERE "Пациент" NOT IN (3, 4, 5, 6);

-- 17. Фильтрация по пациентам и врачам одновременно
SELECT *
FROM "Расписание приёма"
WHERE "Пациент" NOT IN (3, 4, 5, 6) AND "Врач" IN (8, 9);

-- 18. Сортировка врачей по имени по возрастанию
SELECT *
FROM "Врачи"
ORDER BY "Имя" ASC;

-- 19. Сортировка врачей по имени по убыванию
SELECT *
FROM "Врачи"
ORDER BY "Имя" DESC;

-- 20. Сортировка врачей по возрасту
SELECT *
FROM "Врачи"
ORDER BY "Возраст";

-- 21. Минимальный возраст врача
SELECT MIN("Возраст") AS "Мин_возраст"
FROM "Врачи";

-- 22. Максимальный стаж врача
SELECT MAX("Стаж") AS "Макс_стаж"
FROM "Врачи";

-- 23. Средний стаж врачей
SELECT AVG("Стаж") AS "Средний_стаж"
FROM "Врачи";

-- 24. Суммарный вес пациентов в возрасте от 30 до 50 лет
SELECT SUM("Вес") AS "Суммарный_вес"
FROM "Карта пациентов"
WHERE "Возраст" BETWEEN 30 AND 50;

-- 25. Пациенты с именем на букву «А»
SELECT *
FROM "Карта пациентов"
WHERE "Имя" LIKE 'А%';

-- 26. Пациенты со второй буквой «а» в имени
SELECT *
FROM "Карта пациентов"
WHERE "Имя" LIKE '_а%';

-- 27. Пациенты с шаблоном «и_а» в имени
SELECT *
FROM "Карта пациентов"
WHERE "Имя" LIKE '%и_а%';

-- 28. Первые 4 записи из карты пациентов
SELECT *
FROM "Карта пациентов"
LIMIT 4;

-- 29. Количество направлений у врачей (группировка GROUP BY)
SELECT "Врач", COUNT(*) AS "Количество_направлений"
FROM "Направление врача"
WHERE "Направление" BETWEEN 1 AND 10
GROUP BY "Врач";

-- 30. Врачи с более чем одним направлением (фильтрация групп HAVING)
SELECT "Врач", COUNT(*) AS "Количество_направлений"
FROM "Направление врача"
WHERE "Направление" BETWEEN 1 AND 10
GROUP BY "Врач"
HAVING COUNT(*) > 1;
